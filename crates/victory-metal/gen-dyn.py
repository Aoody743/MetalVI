#!/usr/bin/env python3
"""Turns bindgen's static `extern "C"` blocks into functions loaded from
victorymetal.dll on first use, so victory.exe starts (and runs on D3DMetal)
without victorymetal installed, and the unixlib (with its Metal Shader
Converter) is only loaded when the Metal backend is asked for.

usage: gen-dyn.py <bindgen output> <sys.rs>
"""
import re
import sys

src = open(sys.argv[1]).read()

blocks = re.findall(r'unsafe extern "C" \{(.*?)\n\}', src, re.S)
types_only = re.sub(r'unsafe extern "C" \{.*?\n\}\n?', '', src, flags=re.S)

fns = []
for block in blocks:
    for m in re.finditer(r'pub fn (\w+)\((.*?)\)(\s*->\s*([^;]+))?;', block, re.S):
        name, params, _, ret = m.group(1), m.group(2), m.group(3), m.group(4)
        params = ' '.join(params.split()).rstrip(',')
        args = []
        if params:
            depth, cur = 0, ''
            for ch in params:
                if ch in '<([':
                    depth += 1
                elif ch in '>)]':
                    depth -= 1
                if ch == ',' and depth == 0:
                    args.append(cur.strip())
                    cur = ''
                else:
                    cur += ch
            if cur.strip():
                args.append(cur.strip())
        parsed = []
        for a in args:
            n, t = a.split(':', 1)
            parsed.append((n.strip(), t.strip()))
        fns.append((name, parsed, ' '.join(ret.split()) if ret else None))

out = []
out.append('//! Generated by gen-sys.sh (bindgen + gen-dyn.py) from native/victorymetal/src/winemetal.h: do not edit.')
out.append('//! Functions are loaded from victorymetal.dll on first use ([`available`]).')
out.append('#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, dead_code, clippy::all)]')
out.append(types_only)
out.append('''
use std::sync::OnceLock;

static LIBRARY: OnceLock<usize> = OnceLock::new();

/// victorymetal.dll's module handle, loaded on first call (0: not there).
fn library() -> usize {
    *LIBRARY.get_or_init(|| {
        // SAFETY: a NUL-terminated name.
        unsafe { windows_sys::Win32::System::LibraryLoader::LoadLibraryA(b"victorymetal.dll\\0".as_ptr()) as usize }
    })
}

/// Whether victorymetal.dll could be loaded (it is a Wine builtin of the
/// wine running us, see native/victorymetal/build.sh).
pub fn available() -> bool {
    library() != 0
}

/// An export of victorymetal.dll by name (NUL-terminated), or null.
pub fn symbol(name: &[u8]) -> *const core::ffi::c_void {
    let h = library();
    if h == 0 {
        return core::ptr::null();
    }
    // SAFETY: a module handle and a NUL-terminated name.
    unsafe {
        windows_sys::Win32::System::LibraryLoader::GetProcAddress(h as _, name.as_ptr())
            .map_or(core::ptr::null(), |f| f as *const core::ffi::c_void)
    }
}
''')

for name, params, ret in fns:
    ptypes = ', '.join(t for _, t in params)
    rett = f' -> {ret}' if ret else ''
    sig = f'unsafe extern "C" fn({ptypes}){rett}'
    pdecl = ', '.join(f'{n}: {t}' for n, t in params)
    pnames = ', '.join(n for n, _ in params)
    out.append(f'''pub unsafe fn {name}({pdecl}){rett} {{
    static F: OnceLock<usize> = OnceLock::new();
    let f = *F.get_or_init(|| symbol(b"{name}\\0") as usize);
    assert!(f != 0, "victorymetal.dll has no {name} (or is not installed)");
    // SAFETY: the export has the signature winemetal.h declares.
    unsafe {{ core::mem::transmute::<usize, {sig}>(f)({pnames}) }}
}}''')

open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(f'{len(fns)} functions')
